# Helpers
def set_run_font(run, size=12, bold=False):
    run.font.name = 'Times New Roman'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    run.font.size = Pt(size)
    run.bold = bold

def add_paragraph(text="", style=None, first_line=2, line_spacing=1.5, align=None):
    p = doc.add_paragraph(style=style)
    if text:
        r = p.add_run(text)
        set_run_font(r, 12, False)
    fmt = p.paragraph_format
    fmt.first_line_indent = Cm(0.74 * first_line) if first_line else Cm(0)
    fmt.line_spacing = line_spacing
    if align:
        p.alignment = align
    return p

def add_heading(text, level=1):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = p.add_run(text)
    if level == 1:
        set_run_font(r, 16, True)
    elif level == 2:
        set_run_font(r, 14, True)
    else:
        set_run_font(r, 12, True)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    return p

def add_title(text, size=18):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_run_font(r, size, True)
    return p

